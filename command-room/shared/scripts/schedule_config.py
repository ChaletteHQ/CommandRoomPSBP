def _tool_names(tools) -> list:
    """The tool NAMES out of whatever a surface had in hand — a list, a set, a
    mapping keyed by name, or a list of records carrying `name`.

    A deferred stub (`{"name": <id>, "deferred": True}`, or an object carrying
    `deferred` truthy) is a name the host has NOT loaded, so it is not a tool
    yet and is skipped — the same reading `schedule_backend.select_backend`
    gives it, so this guard and that selector answer one list one way
    (SCHEDDISCOVER1 R-SD-4). A loaded tool object is read by its `tool_id`,
    as the selector reads it."""
    if tools is None:
        return []
    if isinstance(tools, dict):
        return [str(k) for k in tools]
    out = []
    try:
        for t in tools:
            if isinstance(t, str):
                out.append(t)
            elif isinstance(t, dict):
                if t.get("deferred"):
                    continue
                name = t.get("name") or t.get("tool")
                if isinstance(name, str):
                    out.append(name)
            elif not getattr(t, "deferred", False):
                name = getattr(t, "tool_id", None)
                if isinstance(name, str) and name:
                    out.append(name)
    except TypeError:
        return []
    return out


