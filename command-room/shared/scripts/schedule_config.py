# -----------------------------------------------------------------------------
# Cron parsing + human-readable rendering
# -----------------------------------------------------------------------------


_DAY_NAMES = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
_DAY_ABBREVS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
_MONTH_NAMES = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]


class CronParseError(ValueError):
    """Raised when a cron expression doesn't parse."""


def _parse_field(field: str, lo: int, hi: int) -> set[int]:
    """Parse a single cron field into the set of integer values it covers.

    Supports: `*`, `N`, `N-M`, `N,M,K`, `*/N`, `N-M/K`. Raises CronParseError
    on anything malformed.
    """
    if field == "*":
        return set(range(lo, hi + 1))

    out: set[int] = set()
    for chunk in field.split(","):
        chunk = chunk.strip()
        if not chunk:
            raise CronParseError(f"empty field segment in {field!r}")

        step = 1
        if "/" in chunk:
            base, step_str = chunk.split("/", 1)
            try:
                step = int(step_str)
            except ValueError:
                raise CronParseError(f"non-int step in {chunk!r}")
            if step < 1:
                raise CronParseError(f"step must be >= 1, got {step}")
            chunk = base.strip() or "*"

        if chunk == "*":
            out.update(range(lo, hi + 1, step))
        elif "-" in chunk:
            try:
                a, b = chunk.split("-", 1)
                a_val, b_val = int(a), int(b)
            except ValueError:
                raise CronParseError(f"bad range in {chunk!r}")
            if a_val > b_val:
                raise CronParseError(f"range start > end in {chunk!r}")
            out.update(range(a_val, b_val + 1, step))
        else:
            try:
                out.add(int(chunk))
            except ValueError:
                raise CronParseError(f"non-int field {chunk!r}")

    bad = [v for v in out if v < lo or v > hi]
    if bad:
        raise CronParseError(f"value(s) {bad} out of range [{lo},{hi}] in {field!r}")
    return out


def parse_cron(expr: str) -> tuple[set[int], set[int], set[int], set[int], set[int]]:
    """Parse a 5-field cron expression. Returns the five field sets.

    Raises CronParseError if expression is malformed.
    """
    if not expr or not isinstance(expr, str):
        raise CronParseError("cron expression must be non-empty string")
    parts = expr.strip().split()
    if len(parts) != 5:
        raise CronParseError(
            f"expected 5 fields (minute hour dom month dow), got {len(parts)}: {expr!r}"
        )
    minute = _parse_field(parts[0], 0, 59)
    hour = _parse_field(parts[1], 0, 23)
    dom = _parse_field(parts[2], 1, 31)
    month = _parse_field(parts[3], 1, 12)
    dow = _parse_field(parts[4], 0, 6)
    return minute, hour, dom, month, dow


def cron_to_english(expr: str) -> str:
    """Render a cron expression as a plain-English label.

    Best-effort — covers the common scheduled-task patterns. Falls back to
    raw cron if pattern is too complex to summarize cleanly.

    Examples:
        "0 7 * * 1-5"      → "7 AM weekdays"
        "30 8 * * 1-5"     → "8:30 AM weekdays"
        "0 7,15 * * 1-5"   → "7 AM and 3 PM weekdays"
        "0 9 * * 1"        → "9 AM Mondays"
        "0 9 * * *"        → "9 AM daily"
        "0 */2 * * 1-5"    → "every 2 hours weekdays"
    """
    try:
        minute_set, hour_set, dom_set, month_set, dow_set = parse_cron(expr)
    except CronParseError:
        return expr  # fall back to raw

    parts = expr.strip().split()
    minute_field, hour_field, dom_field, month_field, dow_field = parts

    # Step expressions ("*/N") get a special-case rendering
    if "/" in hour_field and minute_field == "0" and len(hour_set) > 1:
        try:
            step = int(hour_field.split("/", 1)[1])
        except ValueError:
            step = 1
        time_str = f"every {step} hours" if step > 1 else "hourly"
    else:
        # Simple time render: pick first hour + minute (most cron schedules are
        # single-time or short list)
        if len(hour_set) == 1:
            h = next(iter(hour_set))
            m = next(iter(minute_set)) if len(minute_set) == 1 else 0
            time_str = _format_time(h, m)
        elif len(hour_set) <= 4 and len(minute_set) == 1:
            m = next(iter(minute_set))
            times = [_format_time(h, m) for h in sorted(hour_set)]
            if len(times) == 2:
                time_str = f"{times[0]} and {times[1]}"
            else:
                time_str = ", ".join(times[:-1]) + f", and {times[-1]}"
        else:
            return expr  # too complex; raw cron

    # Day-of-week / day-of-month qualifier
    day_str = _format_day_qualifier(dow_field, dom_field, dow_set, dom_set)

    if day_str:
        return f"{time_str} {day_str}"
    return time_str


def _format_time(hour: int, minute: int) -> str:
    """Format hour+minute as e.g. "7 AM" / "8:30 AM" / "5 PM" / "12:15 PM"."""
    period = "AM" if hour < 12 else "PM"
    h12 = hour % 12 or 12
    if minute == 0:
        return f"{h12} {period}"
    return f"{h12}:{minute:02d} {period}"


def _format_day_qualifier(
    dow_field: str, dom_field: str, dow_set: set[int], dom_set: set[int]
) -> str:
    """Render the day-of-week / day-of-month qualifier as English."""
    # Most common case: dom is "*" and dow is the qualifier
    if dom_field == "*":
        if dow_field == "*":
            return "daily"
        if dow_set == {1, 2, 3, 4, 5}:
            return "weekdays"
        if dow_set == {0, 6}:
            return "weekends"
        if len(dow_set) == 1:
            d = next(iter(dow_set))
            return f"{_DAY_NAMES[d]}s"  # "Mondays", "Fridays"
        if len(dow_set) <= 4:
            names = [_DAY_ABBREVS[d] for d in sorted(dow_set)]
            return ", ".join(names)
        # Too many days, just say "X days/week"
        return f"{len(dow_set)} days/week"

    # dom-restricted (e.g., "1st of month") — less common in our use case
    if dow_field == "*" and len(dom_set) == 1:
        d = next(iter(dom_set))
        suffix = _ordinal_suffix(d)
        return f"on the {d}{suffix} of each month"

    return ""


def _ordinal_suffix(n: int) -> str:
    if 10 <= n % 100 <= 20:
        return "th"
    return {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")


