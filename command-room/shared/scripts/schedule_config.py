def declaration_verdict(current, device_workspace, registered=None) -> dict:
    """BIND3 (D-T2-1, D-T3-1): may THIS seat (its folder at `device_workspace`)
    take the declaration `current` names?

    `{"bound", "holder", "previous_count"}`. Not bound when there is no
    declaration, when it carries no computer digest (an old declaration), when
    this seat knows no folder path (nothing to compare: today's behaviour), or
    when it already names this seat's digest. When it names ANOTHER computer:
    with `registered` (the scheduler's rows, a list) the answer is
    `schedule_backend.seat_records`' - bound when a registered chat sits on
    the declared computer; with no listing (omitted, or anything that is not
    a list) it is bound: the declared computer stays the writer (R-WALK-3).
    A listed record that cannot be placed (no folder, no folder-naming body)
    binds too: an unjudgeable listing never moves the declaration.
    `previous_count` is how many listed records live on the declared
    computer's digest (the took-over sentence's condition, MUST 2)."""
    out = {"bound": False, "holder": None, "previous_count": 0}
    if not isinstance(current, dict):
        return out
    decl_digest = current.get("device_digest")
    here = device_digest(device_workspace)
    if not decl_digest or not here or decl_digest == here:
        return out
    out["holder"] = current.get("device")
    if not isinstance(registered, (list, tuple)):
        out["bound"] = True
        return out
    sb = _schedule_backend()
    # BIND3 fix round 1 (REVIEW N-1): a listed record this module cannot
    # place on a computer (a placeholder, `{}`, a record whose prompt was
    # dropped, a cloud record with `prompt: None`) means the listing cannot
    # judge (c). `seat_records` would file it as this seat's and let the
    # declaration move; here it binds, so the declared computer stays the
    # writer (D-T3-1's safe direction). Cost: a seat whose own chats were
    # made by hand (no folder in their body) is refused until they go.
    if any(not sb.record_device_path(rec) for rec in registered):
        out["bound"] = True
        return out
    split = sb.seat_records(list(registered), abs_path=device_workspace,
                            declaration=current)
    out["previous_count"] = sum(
        1 for rec in split.get("foreign") or []
        if device_digest(sb.record_device_path(rec)) == decl_digest)
    if split.get("bound_elsewhere"):
        out["bound"] = True
        out["holder"] = split.get("holder") or current.get("device")
    return out


