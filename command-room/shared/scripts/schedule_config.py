def device_digest(device_workspace) -> Optional[str]:
    """sha256 of a folder's path on the customer's computer, normalised:
    forward slashes, no trailing slash, the drive letter upper-cased (the
    same folder spelled `c:\\Users\\...` and `C:/Users/.../` is one folder).
    None for an empty path. Two computers with the same account, the same
    folder name AND the same user path digest the same - the honest limit of
    D-4 until a fire carries the device's own name (night 2)."""
    text = str(device_workspace or "").strip().replace("\\", "/").rstrip("/")
    if not text:
        return None
    if len(text) >= 2 and text[1] == ":" and text[0].isalpha():
        text = text[0].upper() + text[1:]
    import hashlib as _hashlib
    return _hashlib.sha256(text.encode("utf-8")).hexdigest()


def _clean_device_name(device_name) -> Optional[str]:
    text = str(device_name or "").strip()
    if not _DEVICE_NAME_RE.match(text) or _ID_SHAPED_RE.match(text):
        return None
    return text


