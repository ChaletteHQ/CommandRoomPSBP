def write_schedule_skipped(workspace_root, reason, now_iso=None) -> dict:
    """ONE `schedule_skipped` row per workspace-local day. Returns {"written"}.

    The guard trips on every fire of every surface that asks — the bridge, the
    registration skill, a change attempt — and a row per ASK would turn one
    fact ("this seat has no scheduler") into a daily pile nobody can read past.
    Once per workspace-local DAY, never per machine day (TZDAY1: a seat in the
    evening Pacific is already tomorrow in UTC, and the row would double).

    The day is read from the ledger through `events_io` — the full-history
    reader every rule says to use — floored by the timestamp's own year so the
    read never opens a shard older than the day it is asking about.

    `reason` must be one of `SCHEDULE_SKIPPED_REASONS`; anything else is
    refused with `{"written": False, "error": "unknown_reason"}` and no row.
    """
    out = {"written": False}
    # The vocabulary is enforced HERE because it cannot be enforced in the
    # schema: `events.schema.json` has no per-type `data` sub-schema mechanism
    # (no `allOf`, no `if`), so the `{scheduler_unavailable,
    # registration_blocked}` enum §7 item 7 asks for is not expressible there
    # (REVIEW_COPY1 M-1, ruling R-COPY1-2). A writer refuses what it does not
    # recognise (§0.34) rather than relabelling it: coercing an unknown reason
    # to `scheduler_unavailable` would have recorded "no scheduler" on a seat
    # whose scheduler was sitting right there, and a wrong fact in an additive
    # ledger is forever.
    if reason not in SCHEDULE_SKIPPED_REASONS:
        out["error"] = "unknown_reason"
        return out
    root = Path(workspace_root)

    if now_iso is None:
        from datetime import datetime as _datetime, timezone as _timezone
        now_iso = (_datetime.now(_timezone.utc)
                   .strftime("%Y-%m-%dT%H:%M:%SZ"))

    import sys as _sys
    _here = str(Path(__file__).resolve().parent)
    if _here not in _sys.path:
        _sys.path.insert(0, _here)

    def _day(ts):
        try:
            from tz import localize_date
            return localize_date(ts or "", root)
        except Exception:  # noqa: BLE001
            return str(ts or "")[:10]

    today = _day(now_iso)
    try:
        import events_io
        for ev in events_io.iter_events(root, since_ts=now_iso):
            if not isinstance(ev, dict) or ev.get("type") != SCHEDULE_SKIPPED:
                continue
            if today and _day(ev.get("ts")) == today:
                out["already_today"] = True
                return out
    except Exception:  # noqa: BLE001 — an unreadable ledger never blocks the say
        pass

    event = {
        "type": SCHEDULE_SKIPPED,
        "source_skill": "enable-command-room-schedules",
        "data": {"reason": reason},
    }
    try:
        from event_gate import append_event
        events_path = root / "_hq" / "data" / "events.jsonl"
        events_path.parent.mkdir(parents=True, exist_ok=True)
        append_event(events_path, event, holder="schedule:scheduler-unavailable")
        out["written"] = True
    except Exception:  # noqa: BLE001
        out["error"] = "append_failed"
    return out


