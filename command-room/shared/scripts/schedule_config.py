#!/usr/bin/env python3
"""
Per-workspace schedule customization (v2.14.10+).

Stores per-task cron schedules in `_hq/data/entities.json` under
`workspace.schedule_config`. Each scheduled-task fire reads this config when
registering or refreshing tasks; if a task isn't in the config, the built-in
default is used.

Operator-driven design: defaults ship sensible for most CEOs; the user (or
the operator running on their behalf) tunes them later via the
`change-schedule` skill or the bridge.

DATA SHAPE
==========

```json
{
  "workspace": {
    "schedule_config": {
      "cr-upcoming-meetings": {
        "cron": "30 6 * * 1-5",
        "label": "6:30 AM weekdays",
        "enabled": true
      },
      "cr-inbox": {"cron": "15 7 * * 1-5", "label": "7:15 AM weekdays", "enabled": true},
      ...
    }
  }
}
```

If `schedule_config` is absent, all tasks use built-in defaults. If a specific
task is missing from the config, that one task uses its default. If `enabled`
is false, that task is skipped at registration time.

A RETIRED-BY-RENAME id additionally carries `"superseded_by": "<successor>"`,
written by `apply_rename_retirement`. It is what tells a reader that this
row's `enabled: false` is the retirement's own bookkeeping rather than a
customer's pause — the two are otherwise identical on disk, and the successor
inheriting the wrong one made a nightly-firing chat invisible to every health
surface. See `load_schedule_config` for the read half.

The `label` field is a human-readable cron summary (e.g., "6:30 AM weekdays").
Generated by `cron_to_english()`. Stored alongside the cron so the change-
schedule skill can show the user what they have without re-deriving.

CRON FORMAT (5-field, WORKSPACE-LOCAL wall clock)
=================================================

The strings here and in a customer's overrides are what the CUSTOMER MEANS —
their own wall clock, never a machine's and never UTC. Which clock a seat
then EVALUATES them in is the seat's question, not this file's, and TZ1 made
it one answer in one place (`shared/scripts/clock_policy.py`):

  * LEGACY desktop seat — the machine clock. Confirmed live 2026-07-01
    (machine=Mountain, workspace=Pacific); `workspace_time_to_machine`
    converts once, at registration, and that has not changed.
  * MERGED / CLOUD seat — UTC, because the platform evaluates a trigger's
    cron in UTC. `schedule_backend.plan_create` / `plan_update` do that ONE
    projection from the workspace zone at registration, and
    `workspace_time_to_machine(backend_id="cloud")` deliberately returns the
    time unchanged so it is never converted twice. Lateness, slot and receipt
    math on that seat reads the WORKSPACE zone, not the container's.

"LOCAL time per Cowork" — the line this block used to open with — was read
as a fact about the whole product; it was only ever true of a desktop seat.

  minute hour day_of_month month day_of_week

  * = any
  N = exact value
  N-M = range
  N,M,K = list
  */N = step

Common patterns:
  "0 7 * * 1-5"      → 7 AM weekdays
  "30 8 * * 1-5"     → 8:30 AM weekdays
  "0 7,15 * * 1-5"   → 7 AM and 3 PM weekdays
  "0 9 * * 1"        → 9 AM Mondays
  "0 9 * * *"        → 9 AM daily

DEFAULTS
========

Built-in defaults for every Command Room scheduled task. These match the
shipped cron expressions in `enable-command-room-schedules` Phase 3.
"""
