def load_schedule_config(entities_json_path: str | Path) -> dict[str, dict]:
    """Read the workspace schedule config from entities.json. Returns a dict
    mapping taskId → {cron, label, enabled} for ALL known tasks (config values
    if set, defaults otherwise). Missing or unreadable entities.json returns
    full defaults.

    Tasks not in DEFAULT_SCHEDULES are NOT included — caller is responsible
    for tasks they introduce post v2.14.10.

    **A RENAMED predecessor's override is INHERITED (EOD2 / REVIEW F-1).** The
    override store is keyed by taskId, and a renamed predecessor's key is no
    longer a DEFAULT_SCHEDULES key — so without this the customer's own hour
    is silently dropped from the merged view, and `schedule_task_id` then
    resolves the predecessor to the successor's SHIPPED DEFAULT. A workspace
    customised to 4 PM that has not taken the rename would be scored against
    the 5 PM default: ~23 hours "late" on every evening fire, a false
    catch-up banner, and `change-schedule` rendering "5 PM weekdays" for a
    chat that fires at 4. Silent, because the orphan-override scan skips a
    key whose id is still registered.

    D-3 carried the ID across the rename; this carries the OVERRIDE KEY, and
    it is the same defect one layer down. The successor's OWN override always
    wins — this only fills a gap, and it is the read-side mirror of the "move
    the override" instruction `change-schedule` already gives the accept path.

    **`cron` and `label` travel; `enabled` travels ONLY from a genuine pause
    (SPEC SCHEDINH1).** This used to inherit the whole dict, on the reasoning
    that "a customer who PAUSED the old id has equally not asked for it to
    come back" — true of a pause, and false of the ONE other thing that
    writes `enabled: false` on a predecessor key. The rename/retirement write
    disables the predecessor as its own bookkeeping and stamps
    `superseded_by: <successor>` alongside; blanket inheritance handed that
    housekeeping flag to the successor as if the customer had asked for it.
    Live consequences on a real workspace, all from one inherited boolean: the
    successor was invisible to the watchdog and every health surface (a firing
    nightly chat that no alarm could see — and the watchdog reports only
    ENABLED tasks, so it structurally cannot see this blind spot), a second
    machine's registration skipped it as "disabled in schedule_config", and
    `change-schedule` rendered a nightly-firing chat as paused.

    The discriminator was always in the dict: a retirement-written override
    carries `superseded_by` naming the id being resolved; a customer pause
    does not. So the carve-out is exact rather than heuristic — an inherited
    override whose `superseded_by` names THIS task contributes cron and label
    and lets `enabled` fall through to the task's default; every other
    inherited override, `superseded_by`-free pause included, behaves exactly
    as before. A `superseded_by` naming some OTHER id is not this task's
    retirement and gets no carve-out either.

    Read-side, deliberately: it fixes every already-affected workspace with
    zero writes (the USERKEY2 read-ladder doctrine). The write-side half —
    the store never being left ambiguous again — is
    `apply_rename_retirement` below. Note the docstring on
    `log_schedule_config_change` states the same rule from the audit side
    ("a customer who paused `past-meetings` did not pause `end-of-day`");
    the two used to disagree, and the live workspace proved that one right.
    """
    config_overrides = {}
    path = Path(entities_json_path)
    if path.exists():
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            workspace = data.get("workspace") or {}
            config_overrides = workspace.get("schedule_config") or {}
        except (json.JSONDecodeError, OSError):
            # Corrupted or unreadable — use defaults
            config_overrides = {}

    merged = {}
    for task_id, default in DEFAULT_SCHEDULES.items():
        override = config_overrides.get(task_id) or {}
        # SCHEDINH1 — True only when the override reached this row by
        # INHERITANCE and carries the retirement's own discriminator. An
        # override the successor owns is never a retirement record, whatever
        # it contains.
        inherited_retirement = False
        if not override:
            for pred in renamed_predecessors(task_id):
                inherited = config_overrides.get(pred) or {}
                if inherited:
                    override = inherited
                    inherited_retirement = (
                        inherited.get(SUPERSEDED_BY_KEY) == task_id)
                    break
        merged[task_id] = {
            "cron": override.get("cron", default["cron"]),
            "label": override.get("label") or cron_to_english(
                override.get("cron", default["cron"])
            ),
            "enabled": (
                default["enabled"]
                if inherited_retirement or "enabled" not in override
                else override["enabled"]
            ),
        }
    return merged


class RenameRetirementError(ValueError):
    """`apply_rename_retirement` was called for something that is not a
    rename. Loud on purpose — see that function's docstring."""


def apply_rename_retirement(workspace_root, predecessor_id: str, *,
                            source_skill: str) -> dict:
    """THE write for the rename-accept path (SPEC SCHEDINH1 DD-2): retire the
    predecessor's schedule override AND give the successor one of its own, in
    one atomic pass, so the store is never left ambiguous.

    WHY THIS IS CODE AND NOT A PARAGRAPH. The instruction already existed in
    prose — `enable-command-room-schedules` Phase 6 tells the accept path to
    carry the customer's override onto the new key — and the live workspace
    that produced this spec had `past-meetings: {enabled: false,
    superseded_by: "end-of-day"}` sitting in its store with no `end-of-day`
    key at all. So the prose ran halfway, or a different path wrote the
    retirement, or it never ran; the record cannot tell us which, and that
    ambiguity IS the argument. A mandate repeated across skill files is a
    mandate presumed skipped (the Bug #98 class this repo keeps re-learning,
    and the same reasoning that made `log_schedule_config_change` a helper
    rather than five paragraphs).

    What it writes, under `workspace.schedule_config` in entities.json:

      <predecessor>  the existing override, plus `enabled: false` and
                     `superseded_by: <successor>` — the retirement's own
                     bookkeeping, kept rather than deleted so the record of
                     WHY the id went quiet survives. `check_registration_drift`
                     already exempts a renamed predecessor's key from the
                     orphan-override scan, so leaving it costs nothing.
      <successor>    `enabled: true` plus the predecessor's `cron`/`label` if
                     it carried any — the customer's customised hour follows
                     the chat across the rename, and the successor is
                     UNAMBIGUOUSLY on under any reader, including one on
                     another machine that predates the SCHEDINH1 read fix.

    A successor that ALREADY has its own override is left alone apart from
    being switched on: its own key is the customer's most recent word about
    that chat and this write has no business restating it.

    LOUD, NOT BEST-EFFORT. `RenameRetirementError` on a predecessor that is
    not a renamed retirement, or whose successor is not a live default — the
    two ways a caller can silently write nonsense into a store whose whole
    problem was a value nobody meant. The audit event stays best-effort per
    RELIABILITY.md (`log_schedule_config_change` swallows its own failure), but
    the store write does not: a retirement that could not be recorded must
    not report success, because the next reader has no way to tell.

    Returns `{"predecessor", "successor", "override", "logged"}`.
    """
    from atomic_write import atomic_write_json

    pred = str(predecessor_id or "").strip()
    successor = (RETIRED_TASKS.get(pred) or {}).get("renamed_to")
    if not successor:
        raise RenameRetirementError(
            f"{pred!r} is not a RENAMED retirement — "
            f"`{RETIREMENT_CLASS_RENAME}` retirements are the only ones with a "
            f"successor to hand an override to. Eliminated and readiness "
            f"retirements have no successor; use the ordinary pause path.")
    if successor not in DEFAULT_SCHEDULES:
        raise RenameRetirementError(
            f"{pred!r} names successor {successor!r}, which is not in "
            f"DEFAULT_SCHEDULES — writing an override for an id no cadence "
            f"governs is exactly the orphan this build exists to stop.")

    path = Path(workspace_root) / "_hq" / "data" / "entities.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RenameRetirementError(
            f"cannot read {path} to record the rename: {exc}") from exc
    if not isinstance(data, dict):
        raise RenameRetirementError(f"{path} is not a JSON object")

    # The SAME container `load_schedule_config` reads. Writing anywhere else
    # would round-trip through no reader at all.
    workspace = data.get("workspace")
    if not isinstance(workspace, dict):
        workspace = {}
        data["workspace"] = workspace
    store = workspace.get("schedule_config")
    if not isinstance(store, dict):
        store = {}
        workspace["schedule_config"] = store

    pred_override = dict(store.get(pred) or {})
    succ_override = dict(store.get(successor) or {})
    if not succ_override:
        # The customer's own hour follows the chat. Only keys they actually
        # set travel — a defaulted cron written here would freeze the shipped
        # default into the store and survive a later default change.
        for key in ("cron", "label"):
            if pred_override.get(key):
                succ_override[key] = pred_override[key]
    succ_override["enabled"] = True

    pred_override["enabled"] = False
    pred_override[SUPERSEDED_BY_KEY] = successor

    store[pred] = pred_override
    store[successor] = succ_override
    atomic_write_json(path, data)

    logged = log_schedule_config_change(
        workspace_root,
        [{"task_id": pred, "cron": pred_override.get("cron"),
          "enabled": False},
         {"task_id": successor, "cron": succ_override.get("cron"),
          "enabled": True}],
        source_skill=source_skill,
        extra_data={"rename_retirement": {"from": pred, "to": successor}})

    return {"predecessor": pred, "successor": successor,
            "override": succ_override, "logged": logged is not None}


def later_add_task_ids() -> frozenset:
    """Default tasks that are deliberately NOT first-install — they need
    accumulated workspace signal before they fire well, and register via the
    existing later-add paths (change-schedule Phase 6 `add` / update-bridge).

    DERIVED, never duplicated: a DEFAULT_SCHEDULES entry outside
    FIRST_INSTALL_TASK_IDS is a later-add by definition. A default entry
    does NOT imply registration — that's the R1 ghost-task lesson
    (relationship-moves rendered as an enabled Sunday task on workspaces
    where it was never added).

    A RETIRED task can never appear here, in any class: retirement takes the
    row OUT of DEFAULT_SCHEDULES, and "not yet added" is the one thing a
    retired surface is not. TASKRET1 is the case that made the distinction
    load-bearing — `commitment-triage`, `pipeline-digest` and `balance` were
    all later-adds the week before, so every surface that treats this set as
    "things worth offering" stops offering them for free.
    """
    return frozenset(DEFAULT_SCHEDULES) - FIRST_INSTALL_TASK_IDS


def registration_target_set(existing_registered) -> frozenset[str]:
    """The set an EXISTING workspace's registration re-run may register
    (`enable-command-room-schedules` Phase 3's non-first-install branch).

    The union `existing | FIRST_INSTALL_TASK_IDS` is what makes a pre-M1
    customer pick up `inbox` on their next re-run without losing anything
    they already have. EOD2 puts one fence around it, and the fence is the
    whole propose-never-auto-apply posture in code:

    **A first-install task whose RENAMED PREDECESSOR is still registered here
    is REMOVED from the target set.** Without it, `end-of-day` — a first-
    install id from the moment EOD2 ships — would auto-register on the next
    registration run of every workspace in the fleet, silently handing each
    customer a SECOND 5 PM chat beside the `past-meetings` one they can see
    in their Scheduled list. That is the add-without-asking violation with a
    new name on it, and it is exactly what M's Decision 9 forbids.

    The rename reaches a workspace one way only: the customer takes the offer
    (`schedule_proposals.propose_task_retirements` →
    `retirement_line("past-meetings")` → `add end of day`). Then the id IS in
    `existing` and this function stops fencing it.

    A retired id already in `existing` stays in the target set on purpose —
    that is what keeps its registered prompt refreshed, and for a RENAMED id
    it is what keeps the old task firing the real pack. A retired id that is
    NOT registered can never enter: retired ids are never in
    FIRST_INSTALL_TASK_IDS.
    """
    existing = frozenset(existing_registered or ())
    target = set(existing | FIRST_INSTALL_TASK_IDS)
    for task_id in FIRST_INSTALL_TASK_IDS - existing:
        if any(pred in existing for pred in renamed_predecessors(task_id)):
            target.discard(task_id)
    return frozenset(target)


def load_schedule_view(
    entities_json_path: str | Path,
    registered_ids,
) -> dict[str, dict]:
    """The registration-aware schedule view (Phase 3 / corrected R1).

    `load_schedule_config` merges defaults + overrides but knows nothing
    about what is actually registered in Cowork's scheduler — so later-add
    tasks rendered as live scheduled tasks on workspaces where they were
    never added (the relationship-moves ghost). This wrapper partitions the
    merged view against the registered-task set.

    Args:
      registered_ids: the registered taskId set. The maintained offline-first
        record is `_hq/workspace_config.json` `registered_taskIds` (written
        by enable-command-room-schedules Phase 0.C and kept current through
        its Phase 3 / Phase 6 flows); pass taskIds from
        the live listing (`schedule_backend.plan_list`) instead when the caller
        has them (fresher). Pass an empty set if neither exists — everything
        then renders as available/not-added, which is the honest answer.

    Returns {task_id: {cron, label, enabled, registered: bool,
    later_add: bool, silent: bool, served_by: str|None}}. NO task should be
    rendered as a live scheduled task unless `registered` is True.

    `registered` is TRUE for a task served by a renamed predecessor (EOD2):
    a workspace running `past-meetings` HAS its evening close, and rendering
    `end-of-day` under "Available, not added yet" would invite the customer
    to register a second 5 PM chat. `served_by` names that predecessor when
    it is what the machine actually has, and is None otherwise — renders use
    it to say "registered as Past Meetings" instead of claiming a taskId the
    Scheduled list does not show.
    """
    registered = set(registered_ids or ())
    later = later_add_task_ids()
    view = {}
    for task_id, spec in load_schedule_config(entities_json_path).items():
        own = task_id in registered
        served_by = None
        if not own:
            for pred in renamed_predecessors(task_id):
                if pred in registered:
                    served_by = pred
                    break
        view[task_id] = {
            **spec,
            "registered": own or served_by is not None,
            "later_add": task_id in later,
            "silent": task_id in SILENT_TASKS,
            "served_by": served_by,
        }
    return view


def workspace_time_to_machine(
    hour: int,
    minute: int,
    workspace_root,
    *,
    backend_id: Optional[str] = None,
) -> tuple[int, int]:
    """Convert a user-requested wall-clock time (workspace TZ — what the
    user MEANS by "8am") to the machine-local time cron must carry (R8:
    cron/fireAt evaluate in MACHINE-local time; workspace TZ is
    presentation-only).

    Uses the CURRENT offset between the two zones (a fixed cron can't track
    DST transitions — when the offset shifts, the fire drifts by the DST
    hour until re-registered; same limitation any fixed cron has). Falls
    back to the unconverted time when the workspace TZ can't resolve —
    machine == workspace is the common case.

    RETIRED ON THE CLOUD BACKEND (BOOT3, 2026-09-19; spec §6 item 4). Pass
    `backend_id="cloud"` — the id `schedule_backend.select_backend` hands back —
    and this returns the time UNCHANGED. On that backend there is no "this
    machine": the trigger lives on the account, the cron is world time, and the
    ONE conversion happens inside `schedule_backend.plan_create` /
    `plan_update`, which projects the workspace-local cron onto UTC with the
    workspace's own zone. Converting here as well would shift the customer's
    8 AM by the container's offset and then again to UTC — two offsets away from
    what they asked for, and a stored cron no verifier could match. Every other
    caller, and every un-merged seat, gets today's body byte for byte.
    """
    if backend_id == "cloud":
        return hour, minute

    import datetime as _dt2

    try:
        from tz import load_workspace_tz

        ws_tz = load_workspace_tz(workspace_path=workspace_root)
        now_machine = _dt2.datetime.now().astimezone()
        # The instant at which the workspace-TZ wall clock reads hour:minute today:
        ws_now = now_machine.astimezone(ws_tz)
        ws_target = ws_now.replace(hour=hour, minute=minute, second=0, microsecond=0)
        machine_target = ws_target.astimezone(now_machine.tzinfo)
        return machine_target.hour, machine_target.minute
    except Exception:
        return hour, minute


def task_display_name(task_id: str) -> str:
    """Map taskId → user-facing display name. Falls back to taskId stripped
    of the `cr-` prefix if not in DISPLAY_NAMES.
    """
    if task_id in DISPLAY_NAMES:
        return DISPLAY_NAMES[task_id]
    return task_id.removeprefix("cr-").replace("-", " ").title()


def serving_display_name(task_id: str) -> str:
    """CUT-PLATE (2026-09-06) — the name of the SURFACE a task id serves.

    A RENAMED predecessor (`past-meetings`) fires the successor's pack
    (`end-of-day`), and the fire introduces itself IN ITS OWN CHAT — the
    lateness banner, the re-run ack, the degrade notice. The v5.28.0
    attended test saw that chat say "your Past Meetings last ran 5:10 PM
    Friday"; M's ruling is that the fire introduces itself as End of Day.
    So the SELF-introduction names the served surface (`renamed_to`), while
    `task_display_name` — the name the customer's Scheduled sidebar shows,
    which the watchdog and the health check deliberately keep (SPEC EOD2)
    — is unchanged. Every other id resolves exactly as before.
    """
    spec = RETIRED_TASKS.get(task_id) or {}
    successor = spec.get("renamed_to")
    if successor:
        return task_display_name(successor)
    return task_display_name(task_id)


