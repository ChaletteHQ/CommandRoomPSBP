def scheduler_availability(tools, *, workspace_root=None, abs_path=None,
                           writer_pair=None, env=None) -> dict:
    """THE guard, called FIRST by every surface that would touch a schedule.

    `tools` is this session's tool list (any iterable of tool-name strings, or
    a mapping whose keys are the names). Returns

        {"available": bool, "reason": str | None, "line": str}

    and is unavailable when EITHER half is:

      * `schedule_backend.select_backend(tools)` is None — no scheduler of any
        kind is visible from this chat (`reason: scheduler_unavailable`), or
      * the SELECTED backend's own `registration_gate()["allowed"]` is False —
        a scheduler is there but Command Room will not register into it yet
        (`reason: registration_blocked`).

    WHOSE gate is the whole question (REVIEW_COPY1 B-1). The module-level
    `schedule_backend.registration_gate()` defaults its `backend_id` to
    `"cloud"`, and the shipped config blocks the cloud row — so a bare module
    call answers "blocked" for EVERY seat, including the whole un-merged
    v5.29.0 desktop fleet, whose scheduler answers perfectly well. The backend
    object knows its own row (`LegacyBackend.registration_gate()` is
    `registration_gate("legacy")`, always allowed), so the guard asks the
    backend it just selected and legacy behaviour stays byte-for-byte today's
    (§0.23, and this lane's own PASS LINE).

    Until BOOT3's module lands, the conservative answer stands: on a tree with
    no `schedule_backend` the guard reports `registration_blocked` with the
    gate's own sentence, which is exactly what the shipped (blocked) config
    says on a merged seat. That is the right way to be wrong — a lane that
    says "I can't set this up" where it could is a nuisance; one that
    registers into a scheduler nothing reaches is eight dead fires a day.

    `workspace_root` is accepted so a caller never has to know which half
    needs it; nothing here reads or writes the workspace.

    SCHEDREG1 (SPEC_V5330_FIXLANES §1 MUST 2): on the CLOUD backend with its
    gate open, the answer also needs a writer pair this process can bake -
    `registration_pair(abs_path or workspace_root, writer_pair=...)`. None ->
    `{"available": False, "reason": "no_account", "line": NO_ACCOUNT_LINE}`:
    a Code tab or an older sandbox that sees the merged app's scheduler but
    has no account of its own must never register a pair-less chat there. The
    legacy backend never asks (byte for byte today's answer).
    """
    try:
        import schedule_backend as _sb
    except ImportError:
        return {"available": False,
                "reason": REASON_REGISTRATION_BLOCKED,
                "line": gate_line()}

    names = _tool_names(tools)
    try:
        selected = _sb.select_backend(names)
    except Exception:  # noqa: BLE001 — a guard never raises into a surface
        selected = None
    backend = selected[0] if isinstance(selected, tuple) else selected
    if backend is None:
        return {"available": False,
                "reason": REASON_NO_SCHEDULER,
                "line": no_scheduler_line()}

    # The gate of the backend that was SELECTED, never the module default.
    try:
        gate = backend.registration_gate()
    except Exception:  # noqa: BLE001
        gate = {"allowed": False}
    if not (isinstance(gate, dict) and gate.get("allowed")):
        return {"available": False,
                "reason": REASON_REGISTRATION_BLOCKED,
                "line": gate_line()}

    if getattr(backend, "id", None) == "cloud":
        pair = registration_pair(abs_path or workspace_root,
                                 writer_pair=writer_pair, env=env)
        if pair is None:
            return {"available": False,
                    "reason": REASON_NO_ACCOUNT,
                    "line": no_account_line()}

    return {"available": True, "reason": None, "line": ""}


