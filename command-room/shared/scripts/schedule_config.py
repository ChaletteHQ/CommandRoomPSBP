def fold_is_active(workspace_root, task_id: str) -> bool:
    """Is `task_id`'s fold — THE PRODUCT'S — currently in effect here? False
    for a task that is not a fold at all (nothing to check), for one whose
    live schedule_config override reads `enabled: True` (the fresh-install
    default, or a customer's own `undo` / `add` having put it back), AND —
    fix round 2 — for one the CUSTOMER switched off themselves.

    FIX ROUND 2, REVIEW_FOLD1A R-3. This used to be `is_folded_fire(id) and
    enabled is False`, which is the CLASS plus "off", and those two facts
    cannot tell the product's act from the customer's. On a seat where
    someone had paused Waiting On by hand, this read True before the fold,
    after it and after the `undo` — so `change-schedule` would have told that
    customer "your Waiting On chat folded into your morning brief" about a
    chat they switched off themselves. A customer's pause is theirs; the fold
    is ours, and a product that cannot tell them apart narrates the wrong one.

    The discriminator is `FOLDED_BY_KEY` on the stored override — the SAME
    device, for the same reason, as SCHEDINH1's `SUPERSEDED_BY_KEY` two
    hundred lines below ("the discriminator that separates the retirement's
    own `enabled: false` bookkeeping from a customer's deliberate pause,
    which the two writes are otherwise indistinguishable from on disk"). It
    is stamped ONLY by `apply_fold_state`, and only when the fold is what
    actually turned the chat off; the reverser takes it away with the rest of
    the override. The merged `load_schedule_config` view never reads it (it
    takes cron/label/enabled and nothing else), so it is inert everywhere
    that is not asking this question.

    This is the ONE check `orchestrator-commitments.md` and
    `orchestrator-my-plate.md`'s Step 0 gate runs — it decides stub vs. full
    chat body PER FIRE, from the workspace's own current state, never from
    a hardcoded "this file is retired forever" assumption (unlike a
    `RETIRED_TASKS` stub): the fold is reversible, so the file has to keep
    asking, not just remember what shipped."""
    if not is_folded_fire(task_id):
        return False
    try:
        view = load_schedule_config(Path(workspace_root) / "_hq" / "data" / "entities.json")
        if (view.get(task_id) or {}).get("enabled") is not False:
            return False
    except Exception:
        return False
    return _fold_override(workspace_root, task_id).get(FOLDED_BY_KEY) == FOLD_REASON


def paused_by_customer(workspace_root, task_id: str) -> bool:
    """The other half of the same question (fix round 2, R-3): this IS a
    folded-fire id, it IS switched off, and the fold is NOT what switched it
    off — so the customer did, and nothing should tell them otherwise.

    `fold_is_active` and this are mutually exclusive by construction and
    neither is the negation of the other: a chat that is simply ON answers
    False to both."""
    if not is_folded_fire(task_id):
        return False
    try:
        view = load_schedule_config(Path(workspace_root) / "_hq" / "data" / "entities.json")
        if (view.get(task_id) or {}).get("enabled") is not False:
            return False
    except Exception:
        return False
    return _fold_override(workspace_root, task_id).get(FOLDED_BY_KEY) != FOLD_REASON


def folded_fire_summary(task_ids) -> str:
    """The ONE line the update bridge posts after the fold migration
    disabled something — the FOLD1A twin of `readiness_retirement_summary`,
    with FOLD1A's own honest framing (a simplification, not a "not ready
    yet"): no `reoffer_when` clause (nothing to wait for) and an explicit
    `undo` mention (the one thing this class promises that readiness does
    not). Empty string for an empty list — most workspaces that never
    registered either chat hear nothing."""
    ids = [t for t in (task_ids or []) if is_folded_fire(t)]
    if not ids:
        return ""
    names = [DISPLAY_NAMES.get(t, t) for t in ids]
    if len(names) == 1:
        listed = names[0]
    elif len(names) == 2:
        listed = f"{names[0]} and {names[1]}"
    else:
        listed = ", ".join(names[:-1]) + f" and {names[-1]}"
    # FIX ROUND 1 (REVIEW_FOLD1A F-7) — the TAIL agrees with the count too.
    # The leading noun was already pluralised and then the sentence forgot:
    # a seat that had already paused Waiting On by hand read "Folded 1
    # scheduled chat … bring THEM back as THEIR OWN CHATS, or ask for
    # EITHER". One chat, four plural words.
    if len(ids) == 1:
        noun, tail = "chat", "bring it back as its own chat, or ask for it"
    elif len(ids) == 2:
        noun, tail = "chats", "bring them back as their own chats, or ask for either"
    else:
        noun, tail = "chats", "bring them back as their own chats, or ask for any of them"
    return (f"Folded {len(ids)} scheduled {noun} into your morning brief: "
            f"{listed} — nothing is lost, say `undo` to {tail} any time.")


def folded_fire_undo_line(task_ids) -> str:
    """The receipt's own `undo` sentence, from the SAME count the summary
    reads (fix round 1, F-7). It used to be a constant claiming "both chats"
    on a seat where only one folded — the receipt is what an operator reads
    back months later, so it may not be the one line that guesses."""
    ids = [t for t in (task_ids or []) if is_folded_fire(t)]
    if len(ids) == 1:
        return "say `undo` — one batch, the chat back exactly as it was"
    if len(ids) == 2:
        return "say `undo` — one batch, both chats back exactly as they were"
    return (f"say `undo` — one batch, all {len(ids)} chats back exactly as "
            f"they were")


class FoldStateError(RuntimeError):
    """The fold's STORE write could not be made. Loud, never best-effort."""


#: The key `apply_fold_state` stamps the pre-fold override under, so `undo`
#: puts the store back to what it actually was rather than to a guess.
FOLD_PREV_OVERRIDES_KEY = "fold_prev_overrides"

#: FIX ROUND 2 (REVIEW_FOLD1A R-3) — the discriminator that separates THE
#: FOLD'S own `enabled: false` from A CUSTOMER'S deliberate pause, which the
#: two writes are otherwise indistinguishable from on disk. Exactly the device
#: SCHEDINH1's `SUPERSEDED_BY_KEY` is, for exactly the same reason, and spelled
#: ONCE for the same reason: the write (`apply_fold_state`) and the two reads
#: (`fold_is_active`, `paused_by_customer`) are halves of one contract, and a
#: literal in each is how they drift apart. The merged `load_schedule_config`
#: view never reads it — it takes cron/label/enabled and nothing else — so it
#: is inert on every path that is not asking whose act this was.
FOLDED_BY_KEY = "folded_by"
#: The one value that key ever carries, and the same string the fold's own
#: `schedule_config_changed` event stamps as its `reason`.
FOLD_REASON = "fold1a_fire_fold"


def apply_fold_state(workspace_root, task_ids, *, enabled: bool,
                     source_skill: str, extra_data: dict | None = None,
                     prev_overrides: dict | None = None) -> dict:
    """THE write for the FOLD1A fold — the STORE and the audit event, in one
    pass, exactly the shape `apply_rename_retirement` uses.

    FIX ROUND 1, REVIEW_FOLD1A F-1. The first cut wrote only
    `log_schedule_config_change`, which is an AUDIT-EVENT writer (its own
    docstring: "THE writer for `schedule_config_changed`"; the lateness
    ledger is its named consumer). It does not touch
    `workspace.schedule_config` in entities.json — and that store is what
    `fold_is_active` reads. The two never met, so the per-fire content-stop
    gate in both orchestrator files evaluated False on every fire, on every
    seat, forever, including the seat the fold had just been applied to. The
    lane's own pins were green over a permanently-False predicate.

    Writes, under `workspace.schedule_config` in entities.json, for every id
    in `task_ids`:

      enabled=False  the existing override, PLUS `enabled: false`. Nothing
                     else is touched — a customer's own cron/label is theirs
                     and this write has no business restating it.
      enabled=True   `prev_overrides[id]` restored VERBATIM when the caller
                     carries it (the key is DELETED again when the id had no
                     override before the fold, so the read falls through to
                     `DEFAULT_SCHEDULES` exactly as it did); `enabled: true`
                     written plainly when it does not.

    LOUD, NOT BEST-EFFORT, same reasoning as `apply_rename_retirement`: the
    audit event stays best-effort per RELIABILITY.md, but a fold that could
    not be recorded in the store must not report success, because the gate
    that reads the store has no way to tell.

    Returns `{"task_ids", "prev_overrides", "logged"}`. `prev_overrides` is
    the pre-write state per id (`None` for an id that had no override) — the
    disable path stamps it on the event so `undo` can restore it exactly.
    """
    from atomic_write import atomic_write_json

    ids = [str(t).strip() for t in (task_ids or []) if str(t or "").strip()]
    if not ids:
        raise FoldStateError("apply_fold_state needs at least one task id")
    for tid in ids:
        if not is_folded_fire(tid):
            raise FoldStateError(
                f"{tid!r} is not in FOLDED_FIRES — this writer only ever "
                f"moves a folded fire's own switch. An id outside the class "
                f"belongs to the ordinary pause path (`change-schedule`), "
                f"which is a decision the customer made, not this one.")

    path = Path(workspace_root) / "_hq" / "data" / "entities.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        data = {}
    except (OSError, json.JSONDecodeError) as exc:
        raise FoldStateError(
            f"cannot read {path} to record the fold: {exc}") from exc
    if not isinstance(data, dict):
        raise FoldStateError(f"{path} is not a JSON object")

    # The SAME container `load_schedule_config` reads. Writing anywhere else
    # would round-trip through no reader at all — which is precisely what
    # went wrong the first time.
    workspace = data.get("workspace")
    if not isinstance(workspace, dict):
        workspace = {}
        data["workspace"] = workspace
    store = workspace.get("schedule_config")
    if not isinstance(store, dict):
        store = {}
        workspace["schedule_config"] = store

    prev: dict = {}
    for tid in ids:
        existing = store.get(tid)
        prev[tid] = dict(existing) if isinstance(existing, dict) else None
        if enabled:
            restore = (prev_overrides or {}).get(tid, "__absent__")
            if restore == "__absent__":
                override = dict(existing) if isinstance(existing, dict) else {}
                override["enabled"] = True
                # FIX ROUND 2 (R-3) — the discriminator goes with the fold it
                # recorded. Leaving it on a re-enabled row would claim the
                # product still had this chat folded, which is the orphan-key
                # class SCHEDINH1 exists to stop. The other two branches drop
                # it for free: they restore the pre-fold override verbatim,
                # and the pre-fold override never carried it.
                override.pop(FOLDED_BY_KEY, None)
                store[tid] = override
            elif restore is None:
                store.pop(tid, None)
            else:
                store[tid] = dict(restore)
        else:
            override = dict(existing) if isinstance(existing, dict) else {}
            # FIX ROUND 2 (R-3) — stamp the discriminator ONLY when the fold
            # is what actually switched this chat off. A chat the CUSTOMER had
            # already paused stays theirs: the fold changes nothing about it,
            # so it must not come away wearing our label and being narrated as
            # our act. (`plan()` already narrows to the live ids when the
            # scheduler readback is in hand; this is the belt for the call
            # that has no readback and passes both ids.)
            if override.get("enabled") is not False:
                override[FOLDED_BY_KEY] = FOLD_REASON
            override["enabled"] = False
            store[tid] = override

    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(path, data)
    except Exception as exc:  # noqa: BLE001 — loud: the gate reads this store
        raise FoldStateError(
            f"cannot write {path} to record the fold: {exc}") from exc

    annotations = dict(extra_data or {})
    if not enabled:
        annotations.setdefault(FOLD_PREV_OVERRIDES_KEY, prev)
    logged = log_schedule_config_change(
        workspace_root,
        [{"task_id": t, "cron": None, "enabled": bool(enabled)} for t in ids],
        source_skill=source_skill, extra_data=annotations)

    return {"task_ids": ids, "prev_overrides": prev,
            "logged": logged is not None}


def is_retired_task(task_id: str) -> bool:
    """True when `task_id` is OUT of the live set — eliminated OR renamed.
    Class membership is the RETIRED_TASKS registry, never a hardcoded name
    list. What every caller needs from this class is the same regardless of
    which kind it is: never offer it, never register it fresh, and never
    report its absence — system-health treats it as "retired, quiet".

    Use `is_renamed_task` to tell the two kinds apart where the difference
    matters: an ELIMINATED task's orchestrator is a retirement stub and its
    work moved to another surface, while a RENAMED task's orchestrator is the
    live successor's file and the old registration keeps firing the real pack
    (EOD2)."""
    return task_id in RETIRED_TASKS


def is_renamed_task(task_id: str) -> bool:
    """True when `task_id` was RENAMED into a live successor rather than
    eliminated. Membership is the `renamed_to` field on the RETIRED_TASKS
    row — never a name list."""
    return bool((RETIRED_TASKS.get(task_id) or {}).get("renamed_to"))


# The three retirement classes. `retirement_class()` returns one of these for
# a retired id and "" for a live one — callers branch on the RETURN VALUE,
# never on a name they remember.
RETIREMENT_CLASS_ELIMINATION = "elimination"
RETIREMENT_CLASS_RENAME = "rename"
RETIREMENT_CLASS_READINESS = "readiness"

# SPEC SCHEDINH1 — the key a RETIREMENT stamps on the predecessor's schedule
# override, naming the successor that replaced it. It is the discriminator
# that separates the retirement's own `enabled: false` bookkeeping from a
# customer's deliberate pause, which the two writes are otherwise
# indistinguishable from on disk. Spelled ONCE: the read carve-out in
# `load_schedule_config` and the write in `apply_rename_retirement` are the
# two halves of one contract, and a literal in each is how they drift apart.
SUPERSEDED_BY_KEY = "superseded_by"


def retirement_class(task_id: str) -> str:
    """Which KIND of retirement `task_id` is — the one dispatch point.

    Returns `""` for a task that is not retired, else one of
    `RETIREMENT_CLASS_ELIMINATION` / `_RENAME` / `_READINESS`.

    Derivation order matters. An explicit `retirement_class` field on the row
    WINS, because the readiness class is a deliberate posture choice that no
    other field implies. Absent that field the class is derived exactly as it
    always was — `renamed_to` present means rename, absent means elimination —
    so the pre-TASKRET1 rows keep their behaviour without being re-annotated,
    and a future row that forgets the field degrades to the SAFE class
    (elimination = propose, never silent) rather than to the acting one.

    That default direction is the whole safety property here: a typo in the
    class marker costs a customer one proposal they can ignore, never a chat
    disabled without being asked.
    """
    spec = RETIRED_TASKS.get(task_id)
    if not spec:
        return ""
    declared = (spec.get("retirement_class") or "").strip()
    if declared:
        return declared
    return (RETIREMENT_CLASS_RENAME if spec.get("renamed_to")
            else RETIREMENT_CLASS_ELIMINATION)


def is_readiness_retirement(task_id: str) -> bool:
    """True when `task_id` came out because its SUBSTRATE wasn't ready
    (SPEC TASKRET1) — the class the update bridge APPLIES rather than
    proposes. Membership is `retirement_class`, never a name list."""
    return retirement_class(task_id) == RETIREMENT_CLASS_READINESS


def readiness_retired_task_ids() -> frozenset[str]:
    """Every readiness-retired id. DERIVED from the registry so the bridge
    migration, the tests and any future surface all read one list."""
    return frozenset(t for t in RETIRED_TASKS if is_readiness_retirement(t))


def reoffer_condition(task_id: str) -> str:
    """The customer-facing condition under which a readiness-retired surface
    COMES BACK. Empty string for every other class — nothing else makes this
    promise, and inventing one would be a commitment the product hasn't made.

    This is the field that separates a readiness retirement from a silent
    `SUPERSEDED_BY` disable: the customer is told the surface is on loan, not
    deleted, and told what redeems it."""
    if not is_readiness_retirement(task_id):
        return ""
    return (RETIRED_TASKS.get(task_id) or {}).get("reoffer_when", "")


def renamed_predecessors(task_id: str) -> tuple[str, ...]:
    """The retired ids that were RENAMED INTO `task_id` — the inverse of
    `renamed_to`, derived so there is no second map to keep in step.

    A registered predecessor SERVES its successor: same orchestrator file,
    same pack, same receipt series. Callers use this to answer "is this task
    covered on this machine?" without asking the customer to re-register
    anything (`serving_task_ids` is the convenience wrapper)."""
    return tuple(sorted(
        tid for tid, spec in RETIRED_TASKS.items()
        if spec.get("renamed_to") == task_id
    ))


def schedule_task_id(task_id: str) -> str:
    """The id whose DEFAULT_SCHEDULES row governs `task_id`'s CADENCE.

    Identity for every live id, and for a retired id that was eliminated (it
    has no cadence — nothing should be asking). For a RENAMED retired id it
    is the SUCCESSOR: the predecessor left DEFAULT_SCHEDULES, but the task it
    names is still registered and still firing, on the successor's cron,
    because they are the same chat at the same hour.

    Anything that asks "when should this have fired?" must resolve through
    here. `late_fire` is the case that proved it: on the day EOD2 shipped,
    every un-renamed machine's evening fire would have looked up
    `past-meetings`, found no row, and returned tier `unknown` — lateness
    detection and the catch-up banner silently off for the whole fleet, on
    the one chat that fires last thing every weekday.
    """
    successor = (RETIRED_TASKS.get(task_id) or {}).get("renamed_to")
    if successor and successor in DEFAULT_SCHEDULES:
        return successor
    return task_id


def serving_task_ids(task_id: str) -> tuple[str, ...]:
    """`task_id` plus every registered-id that would serve it — itself first.

    The order matters for readers that take the first match: the current id
    wins, a renamed predecessor is the fallback."""
    return (task_id,) + renamed_predecessors(task_id)


def is_task_served(task_id: str, registered_ids) -> bool:
    """True when `task_id`'s work is covered by what is REGISTERED here —
    either under its own id or under a renamed predecessor's.

    This is the check that keeps a rename from reading as breakage. A
    workspace still running `past-meetings` has an evening close; saying its
    `end-of-day` chat is "missing from the schedule" would be false, and
    acting on it would register a second 5 PM chat."""
    registered = set(registered_ids or ())
    return any(tid in registered for tid in serving_task_ids(task_id))


def cron_time_phrase(expr: str) -> str:
    """The clock half of a cron's English label — "5 PM" from
    `0 17 * * 1-5`. Empty string when the expression doesn't parse or names
    more than one time.

    Exists so customer copy can quote a task's hour without typing it: a
    hand-typed hour in a retirement sentence is a second copy of the cron,
    and it goes stale the first time the default moves."""
    try:
        minute_set, hour_set, _dom, _month, _dow = parse_cron(expr)
    except CronParseError:
        return ""
    if len(hour_set) != 1 or len(minute_set) != 1:
        return ""
    return _format_time(next(iter(hour_set)), next(iter(minute_set)))


def retirement_reason(task_id: str) -> str:
    """The retired task's `reason`, with any registry placeholder resolved.

    A RENAME entry's reason carries `{time}` so the hour is read from the
    successor's own cron rather than typed twice. Callers that surface the
    reason on its own (the proposal record, telemetry) must go through here
    — handing a raw `{time}` to a customer-facing string is the failure this
    exists to prevent."""
    spec = RETIRED_TASKS.get(task_id)
    if not spec:
        return ""
    reason = spec.get("reason", "")
    successor = spec.get("renamed_to")
    if successor and "{time}" in reason:
        phrase = cron_time_phrase(
            (DEFAULT_SCHEDULES.get(successor) or {}).get("cron", "")
        ) or "same-time"
        reason = reason.replace("{time}", phrase)
    return reason


def retirement_line(task_id: str) -> str:
    """The ONE customer-facing sentence for a retired task.

    Built from the registry so the wording cannot drift between the bridge,
    change-schedule, registration and system-health. Empty string for a task
    that is not retired — callers surface nothing rather than inventing a
    line.

    THREE SHAPES, and the registry picks (EOD2, extended by TASKRET1):

      * ELIMINATED (`pulse`, `upcoming-meetings`) — the chat is gone and the
        line offers the `pause` that clears it.
      * RENAMED (`past-meetings` → `end-of-day`) — the chat is NOT gone, so a
        "your chat is retired" sentence would be a lie about a task that
        fires tonight. The line says what it is called now, quotes the hour
        FROM the successor's own cron, and offers the switch.
      * READINESS (`commitment-triage`, `pipeline-digest`, `balance`) — the
        update has ALREADY switched it off, so the line must not ask for a
        `pause` the customer no longer has to perform; offering one would be
        the product asking for a tap it already took. It states what
        happened, why, where the same work still lives on demand, and — the
        clause only this class carries — what brings the chat back.

    The readiness branch reads its optional clauses with `.get`, never
    `[...]`. This is the ONE customer-facing renderer, and it is reached from
    four places (the three stubs, change-schedule's `add` refusal, the bridge
    ack, and every `plan_readiness_retirements` entry's `line`). A row that
    forgets `replacement` or `reoffer_when` must therefore DEGRADE to a
    shorter sentence that is still true, not raise `KeyError` in front of a
    customer — the same discipline the suite applies to its own reads. A
    complete row renders byte-identically to the hardcoded form.
    """
    spec = RETIRED_TASKS.get(task_id)
    if not spec:
        return ""
    name = DISPLAY_NAMES.get(task_id, task_id)
    kind = retirement_class(task_id)
    if kind == RETIREMENT_CLASS_READINESS:
        # `retirement_reason`, not the raw field — identical output today
        # (readiness rows carry no placeholder), and the ONE place a future
        # placeholder gets resolved rather than handed to a customer raw.
        reason = (retirement_reason(task_id) or "").strip()
        replacement = (spec.get("replacement") or "").strip()
        reoffer = (spec.get("reoffer_when") or "").strip()
        line = (f"Your {name} chat is off the schedule — {reason}."
                if reason else f"Your {name} chat is off the schedule.")
        if replacement:
            line += f" {replacement}."
        if reoffer:
            line += f" It comes back when {reoffer}."
        return line
    successor = spec.get("renamed_to")
    if successor:
        new_name = DISPLAY_NAMES.get(successor, successor)
        return (f"Your {name} chat is now {new_name} — "
                f"{retirement_reason(task_id)}. {spec['replacement']}.")
    return (f"Your {name} chat is retired — {spec['reason']}. Say "
            f"`pause {name.lower()}` and I'll switch it off; {spec['replacement']}.")


def readiness_retirement_summary(task_ids) -> str:
    """The ONE line the update bridge posts after the readiness migration
    disabled something (SPEC TASKRET1 §2.4). Empty string for an empty list —
    a workspace that had none of the three hears NOTHING, which is the
    behaviour on the overwhelming majority of installs.

    Composed here rather than typed in the bridge for the reason every other
    retirement string is: the wording has to be identical wherever it appears,
    and a sentence hand-typed into a SKILL.md is a second copy that drifts on
    the first edit. The per-task `reoffer_when` clauses are what make this an
    ACK rather than a silent disable — drop them and this class becomes
    `SUPERSEDED_BY` with extra steps.

    Ids that are not readiness retirements are ignored, not rendered: this
    line promises a return, and only this class has one to promise.
    """
    ids = [t for t in (task_ids or []) if is_readiness_retirement(t)]
    if not ids:
        return ""
    names = [DISPLAY_NAMES.get(t, t) for t in ids]
    if len(names) == 1:
        listed = names[0]
    elif len(names) == 2:
        listed = f"{names[0]} and {names[1]}"
    else:
        listed = ", ".join(names[:-1]) + f" and {names[-1]}"
    noun = "chat" if len(ids) == 1 else "chats"
    head = (f"Switched off {len(ids)} scheduled {noun} that need more "
            f"groundwork first: {listed}.")
    tail = " ".join(
        f"{DISPLAY_NAMES.get(t, t)} comes back when {reoffer_condition(t)}."
        for t in ids
    )
    return f"{head} {tail}"


