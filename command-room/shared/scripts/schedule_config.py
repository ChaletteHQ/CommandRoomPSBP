def scheduled_writer(workspace_root) -> Optional[dict]:
    """The workspace's declared scheduled writer, or None.

    `{"writer_id", "declared_at", "declared_by"}` read from
    `workspace.scheduled_writer` through `connector_config.workspace_block`
    (the one reader that honours both the nested and the flat entities shape)
    — never a raw parse. READ ONLY, and it never raises: an absent file, an
    absent key, or a stored id of the wrong shape all answer None, which every
    caller reads as "no declaration" — today's behaviour.
    """
    try:
        ws = _connector_config().workspace_block(workspace_root)
    except Exception:  # noqa: BLE001 — a reader never raises into a fire
        return None
    row = ws.get(SCHEDULED_WRITER_KEY) if isinstance(ws, dict) else None
    if not isinstance(row, dict):
        return None
    writer = str(row.get("writer_id") or "").strip()
    if not _SCHEDULED_WRITER_ID_RE.match(writer):
        return None
    declared_at = row.get("declared_at")
    declared_by = row.get("declared_by")
    out = {
        "writer_id": writer,
        "declared_at": declared_at if isinstance(declared_at, str) else None,
        "declared_by": declared_by if isinstance(declared_by, str) else None,
    }
    # HYGIENE3 (D-4): the computer, when the declaration carries it. An old
    # declaration without one reads exactly as before - no key added.
    device = _clean_device_name(row.get("device"))
    digest = row.get("device_digest")
    if device:
        out["device"] = device
    if isinstance(digest, str) and re.match(r"^[0-9a-f]{64}$", digest):
        out["device_digest"] = digest
    # BRIDGE2 (Train 2 §4 MUST 2, F-OFF-1): the computer the declaration was
    # taken FROM, when it moved between computers. Read only when stored.
    prev_device = _clean_device_name(row.get("previous_device"))
    prev_digest = row.get("previous_device_digest")
    if prev_device:
        out["previous_device"] = prev_device
    if isinstance(prev_digest, str) and re.match(r"^[0-9a-f]{64}$", prev_digest):
        out["previous_device_digest"] = prev_digest
    return out


def declare_scheduled_writer(workspace_root, writer_id=None, *,
                             declared_by: str, now_iso=None,
                             device_name=None, device_workspace=None,
                             registered=None) -> dict:
    """Declare THIS workspace's one scheduled writer — THE writer for that act.

    `writer_id` is an `acct-` + twelve-hex id, or None for "this seat's own
    writer id" (`writer_identity.writer_id`, which on a merged seat is the id
    the access layer forwarded to the host that holds the data). A seat with
    no writer id — every legacy and local seat — declares NOTHING and answers
    `error: "no_writer_id"`: only a seat that can name itself may claim the
    schedule.

    Writes `workspace.scheduled_writer = {writer_id, declared_at,
    declared_by}` through `atomic_write_json_locked` (the `_workspace_container`
    site DISC1's setter uses — nested or flat, whichever the file already has),
    then appends ONE `scheduled_writer_declared` row carrying `writer_id`,
    `previous` (the id it replaced, or None) and `declared_by`.

    IDEMPOTENT. When the stored declaration already names this id, NOTHING is
    written — no file write, no row — and `changed` is False. That is what lets
    the update bridge ask on every run without stamping the book every run.

    PER COMPUTER (HYGIENE3, R-RW3-2, D-4). `device_name` is the computer's
    name as `get_device_info` reports it; `device_workspace` is the folder's
    path on that computer - the `CR_DEVICE_WORKSPACE` the access layer
    forwards on every rendered line, read from the environment when the
    caller passes none (a path argument would be fenced by the door, which
    refuses a path outside the workspace). Both land on the declaration and
    its row as `device` and `device_digest` (`device_digest()`). The same id
    from a DIFFERENT folder path is a different computer: it re-declares.
    The same id and the same path with no device recorded yet adds them once.
    A seat that knows neither declares exactly as before.

    BOUND ELSEWHERE (BIND3, D-T2-1, D-T3-1). When the declaration names
    ANOTHER computer's digest, this seat takes it only when nothing is
    registered on that computer: `registered` is the scheduler's rows (the
    listing the caller already read); `declaration_verdict` judges them
    through `schedule_backend.seat_records`. With a chat on the declared
    computer - or with no listing handed in - NOTHING is written and the
    answer is `{changed: False, reason: "bound_elsewhere", line, invite}`:
    `line` names the holder (`bound_elsewhere_declare_line`), `invite` is the
    producer's setup sentence (`bound_elsewhere_invite`). The caller says
    both, once.

    Returns `{changed, writer_id, previous, declared_at, event_written, line,
    error}`. `line` is the `declared` sentence when — and only when — a
    declaration was written this call, so the caller says it once.
    """
    out = {"changed": False, "writer_id": None, "previous": None,
           "declared_at": None, "event_written": False, "line": "",
           "invite": "",
           "error": None}
    who = str(declared_by or "").strip()
    if not who:
        out["error"] = "declared_by must be a non-empty string"
        return out
    if writer_id is None:
        try:
            import writer_identity as _wi
        except ImportError:
            import sys as _sys
            _sys.path.insert(0, str(Path(__file__).resolve().parent))
            import writer_identity as _wi
        try:
            writer_id = _wi.writer_id(workspace_root)
        except Exception:  # noqa: BLE001
            writer_id = None
        if not writer_id:
            out["error"] = "no_writer_id"
            return out
    writer = str(writer_id).strip()
    if not _SCHEDULED_WRITER_ID_RE.match(writer):
        out["error"] = "bad_writer_id"
        return out
    out["writer_id"] = writer
    if device_workspace is None:
        import os as _os
        device_workspace = _os.environ.get(DEVICE_WORKSPACE_ENV)
    device = _clean_device_name(device_name)
    digest = device_digest(device_workspace)

    current = scheduled_writer(workspace_root)
    if current is not None and current["writer_id"] == writer:
        same_place = (digest is None
                      or current.get("device_digest") == digest)
        same_name = device is None or current.get("device") == device
        if same_place and same_name:
            out["declared_at"] = current["declared_at"]
            return out  # already declared — no write, no row
    # BIND3 (D-T2-1, D-T3-1): another computer holds the declaration - move
    # it only when no registered chat sits there; otherwise refuse, write
    # nothing, and hand back the one sentence naming the holder.
    verdict = declaration_verdict(current, device_workspace, registered)
    if verdict["bound"]:
        out["reason"] = REASON_DECLARE_BOUND_ELSEWHERE
        out["line"] = bound_elsewhere_declare_line(verdict["holder"])
        out["invite"] = bound_elsewhere_invite(workspace_root)
        return out
    previous = current["writer_id"] if current is not None else None
    out["previous"] = previous
    # BRIDGE2 (Train 2 §4 MUST 2, F-OFF-1): a declaration that moves off a
    # computer the old one named carries that computer - its name and its
    # folder digest - so the takeover is visible on the book, not only the
    # account id (which is the same for two computers of one account).
    took_from = {}
    if current is not None and (current.get("device") or current.get("device_digest")):
        if (current.get("device_digest") != digest
                or (device is not None and current.get("device") != device)):
            if current.get("device"):
                took_from["previous_device"] = current["device"]
            if current.get("device_digest"):
                took_from["previous_device_digest"] = current["device_digest"]
    out.update(took_from)

    cc = _connector_config()
    path = cc._entities_path(workspace_root)
    if not path.is_file():
        # Never mint an entities.json that holds nothing but this key.
        out["error"] = "no_entities"
        return out
    ent = cc._load_full(workspace_root)
    if not ent:
        out["error"] = "entities_unreadable"
        return out
    if now_iso is None:
        from datetime import datetime as _datetime, timezone as _timezone
        now_iso = (_datetime.now(_timezone.utc)
                   .strftime("%Y-%m-%dT%H:%M:%SZ"))
    ws = cc._workspace_container(ent)
    row = {"writer_id": writer, "declared_at": now_iso, "declared_by": who}
    if device:
        row["device"] = device
    if digest:
        row["device_digest"] = digest
    row.update(took_from)
    ws[SCHEDULED_WRITER_KEY] = row
    ent["last_writer"] = who
    ent["last_updated"] = now_iso
    try:
        cc._write_entities(workspace_root, ent, holder=f"schedule:{who}")
    except Exception as exc:  # noqa: BLE001
        out["error"] = f"{type(exc).__name__}: {exc}"
        return out
    out["changed"] = True
    out["declared_at"] = now_iso
    out["line"] = declared_line(device)
    out["invite"] = ""
    # BRIDGE2 (Train 2 §4 SHOULD, F-OFF-1): taken from ANOTHER named
    # computer, the line names it only when that computer still had chats
    # listed (BIND3 MUST 2, N-3: `previous_count` from `seat_records`);
    # `invite` is the producer's setup sentence the bridge says after it.
    # On THIS path the took-over branch is unreachable (a count >= 1 means
    # `declaration_verdict` bound and refused above); it is reachable only
    # through the deferred explicit takeover verb (spec §5, BRIDGE2 S-6).
    # `run_t3_bind3_test` (2f) keeps the producer pinned (REVIEW N-4).
    prev_name = took_from.get("previous_device")
    if prev_name and device and _clean_device_name(prev_name) != device:
        out["line"] = took_over_line(device, prev_name,
                                     verdict["previous_count"])
        if out["line"] != declared_line(device):
            out["invite"] = took_over_invite(workspace_root)

    event = {
        "type": SCHEDULED_WRITER_DECLARED,
        "source_skill": who,
        "data": {"writer_id": writer, "previous": previous,
                 "declared_by": who},
    }
    if device:
        event["data"]["device"] = device
    if digest:
        event["data"]["device_digest"] = digest
    event["data"].update(took_from)
    try:
        import sys as _sys
        _here = str(Path(__file__).resolve().parent)
        if _here not in _sys.path:
            _sys.path.insert(0, _here)
        from event_gate import append_event

        events_path = Path(workspace_root) / "_hq" / "data" / "events.jsonl"
        append_event(events_path, event, holder=f"schedule:{who}")
        out["event_written"] = True
    except Exception:  # noqa: BLE001 — the record never undoes the declaration
        out["error"] = "append_failed"
    return out


